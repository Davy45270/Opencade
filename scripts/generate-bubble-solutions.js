/* global console, performance, URL */
import './ts-loader.js';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const { solveLevel } = await import('./bubble-solver.ts');
const solutions = [], started = performance.now();
for (let level = 0; level < 30; level++) {
    const result = solveLevel(level, 28, 160);
    assert.ok(result.won, `L${level + 1}`);
    solutions.push(result.sequence);
    console.log(`L${level + 1}: ${result.shots} shots, ${(performance.now()-started).toFixed(0)} ms`);
}
writeFileSync(new URL('../tests/bubble-solutions.ts', import.meta.url),
    '// Generated by scripts/generate-bubble-solutions.js; seed 28.\n' +
    'export const solutions: readonly (readonly { angle: number; swap: boolean }[])[] = [\n' +
    solutions.map(shots => '    ' + JSON.stringify(shots)).join(',\n') + '\n];\n');
