/* global console, process, URL */
import './ts-loader.js';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const { Engine } = await import('../src/engines/derapage/engine.ts');
const { humanRun } = await import('./derapage-human.js');
const { kartPilot, kartWitness, replayKart } = await import('../tests/level-catalogue-kart-replay.ts');
export function recordKart(level, mode, frameLimit=12000) {
    // Identical seeded heading noise and nine-frame (150 ms) delayed pilot to Z36.
    const human=mode === 'joystick' ? humanRun(level,true,undefined,Engine,frameLimit) : undefined;
    const seed=28;
    const e=new Engine(level,seed), inputs=[], shortcut=level===17 && mode==='keyboard';
    let last='';
    for (let frame=0;frame<frameLimit && e.status==='playing';frame++) {
        const input=human
            ? { steer:0,drift:false,bonus:false,mode:'joystick',heading:human.events[Math.floor(frame/9)],assist:true }
            : kartPilot(e,shortcut);
        assert(input.heading !== undefined || !human,'human tape exhausted');
        const event=human ? [frame,input.heading] : [frame,input.steer,input.bonus ? 1 : 0];
        const signature=JSON.stringify(event.slice(1));
        if (signature!==last) { inputs.push(event); last=signature; }
        e.input(input); e.step(1000/60);
    }
    if(frameLimit===12000) assert.equal(e.status,'won',`${level}/${mode}`);
    const record={level,seed,mode,shortcut,frames:e.frames,inputs,result:kartWitness(e),laps:e.lapTimesMs,score:e.score};
    if(frameLimit===12000) replayKart(record);
    return record;
}
if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
const records=[];
for (const level of [17,19,26]) for (const mode of ['keyboard','joystick']) {
    const record=recordKart(level,mode); records.push(record);
    const e={frames:record.frames,lapTimesMs:record.laps};
    console.log(`${level}/${mode}: ${e.frames} frames, laps ${e.lapTimesMs.map(n=>(n/1000).toFixed(2))}`);
}
writeFileSync('tests/level-catalogue-kart-recordings.ts', '// Generated by nice -n 19 ionice -c3 node scripts/record-level-catalogue-kart.js\nimport type { KartRecording } from \'./level-catalogue-kart-replay\';\nexport const kartRecords: KartRecording[] = [\n'+records.map(r=>JSON.stringify(r)).join(',\n')+'\n];\n');

}
