/* global process, URL */
import './ts-loader.js';
const { Engine } = await import('../src/engines/derapage/engine.ts');
const { nearest } = await import('../src/engines/derapage/track.ts');
const { Random } = await import('../src/engines/shared/random.ts');
const { circuits } = await import('../src/engines/derapage/circuits.ts');
export function humanRun(level, assist = true, recording, EngineType = Engine, frameLimit=18000) {
    const e = new EngineType(level, 28), k = e.karts[0], t = e.track, random = new Random(67);
    let off = 0, stopped = 0, longest = 0, frame = 0, heading = k.angle, pending = k.angle;
    const events = [];
    for (; frame < frameLimit && k.lap < 3; frame++) {
        if (frame % 9 === 0) {
            if (recording) heading = recording[frame / 9];
            else {
                heading = pending;
                const n = nearest(t, k), target = t.points[(n.index + 6) % 96];
                pending = Math.atan2(target.y - k.y, target.x - k.x) + (random.next() * 2 - 1) * .35;
            }
            events.push(heading);
        }
        e.input({ steer: 0, drift: false, bonus: false, mode: 'joystick', heading, assist });
        e.step(1000 / 60);
        const n = nearest(t, k);
        if (n.distance > t.widths[n.index] / 2) off++;
        stopped = Math.hypot(k.vx, k.vy) < 2 ? stopped + 1 : 0;
        longest = Math.max(longest, stopped);
    }
    return { level, name: t.circuit.name, laps: k.lap, longestStop: longest / 60, off: off / frame, frames: frame, final: { x: k.x, y: k.y, angle: k.angle }, events };
}
export const humanLevels = [0, 2, 14, circuits.findIndex(c => c.name === 'Le Rocher')];

// Run explicitly to regenerate the checked-in, seeded 150 ms input tapes.
if (process.argv.includes('--record')) {
    const { writeFileSync } = await import('node:fs');
    const recordings = humanLevels.map(level => humanRun(level));
    writeFileSync(new URL('../tests/derapage-recordings.ts', import.meta.url),
        '// Generated by nice -n 19 ionice -c3 node scripts/derapage-human.js --record\n' +
        'export const recordings = ' + JSON.stringify(recordings) + ';\n');
}
