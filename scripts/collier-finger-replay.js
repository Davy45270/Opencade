/* global console, process */
import assert from 'node:assert/strict';
import { runInNewContext } from 'node:vm';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { Finger, checksum } from '../tests/e2e/finger-stepped.ts';
import { driveCollier } from '../tests/e2e/collier-stepped-driver.ts';
import { createScene } from './collier-scene-oracles.js';

/** Same helper and pilot, real scene listeners; only the DOM/CDP transport is doubled. */
export async function replayCollier(level, box = { x: 20, y: 44, width: 350, height: 350 * 736 / 360 }, resume = { x: 100, y: 350, width: 190, height: 56 }, resumeEvents, geometry) {
    const { scene, hook, handlers, domHandlers } = createScene('panda', false, undefined, geometry?.canvas);
    scene.session.paused = true;
    const canvas = geometry?.canvas ?? hook.geometry().canvas;
    const input = geometry?.input ?? { x: box.x, y: box.y, scaleX: canvas.width / box.width, scaleY: canvas.height / box.height };
    const window = { __ARCADE_TEST__: { current: () => 'collier', games: { collier: hook } } };
    const rect = selector => selector === '#resume' ? resume : box;
    const document = {
        querySelector: selector => ({ getBoundingClientRect: () => rect(selector) }),
        elementFromPoint: (x, y) => ({ closest: selector => {
            const b = rect(selector);
            return x >= b.x && y >= b.y && x <= b.x + b.width && y <= b.y + b.height;
        } })
    };
    const page = {
        clock: { pauseAt: async () => {}, runFor: async () => {} },
        evaluate: async (fn, arg) => runInNewContext(`(${fn.toString()})(arg)`, { window, document, arg })
    };
    let active = [];
    const transport = [];
    let resumed = false;
    const cdp = { send: async (_method, { type, touchPoints }) => {
        const points = type === 'touchEnd' ? active : touchPoints;
        const name = { touchStart: 'pointerdown', touchMove: 'pointermove', touchEnd: 'pointerup' }[type];
        for (const point of points) {
            // The button may have a fractional DOM centre. All canvas targets
            // are integer CSS pixels, independently regenerated by the shared pilot.
            const delivered = !resumed && resumeEvents ? resumeEvents.find(event => event.type === name) : point;
            assert.ok(delivered, 'Resume transport receipt');
            assert.ok(Math.abs(delivered.x - point.x) < 1 && Math.abs(delivered.y - point.y) < 1);
            transport.push({ type: name, x: delivered.x, y: delivered.y });
            domHandlers.get(name)?.({ pointerType: 'touch', clientX: delivered.x, clientY: delivered.y });
            if (resumed) handlers.get(name)({ id: point.id, wasTouch: true,
                x: (point.x - input.x) * input.scaleX,
                y: (point.y - input.y) * input.scaleY,
                downTime: 0, upTime: 100 });
        }
        if (!resumed && type === 'touchEnd') { scene.session.paused = false; resumed = true; }
        active = touchPoints;
    } };
    const finger = await Finger.create(page, cdp, 300);
    await finger.press(['#resume']);
    hook.loadLevel(level, 300);
    await finger.read();
    const swaps = await driveCollier(finger, { readDriver: async () => hook.readDriver() }, geometry ?? hook.geometry(), box);
    await finger.release();
    let result;
    await finger.attach({ attach: async (_name, { body }) => { result = JSON.parse(body); } });
    assert.equal(result.outcome, 'won', `Niveau ${level + 1}`);
    assert.equal(result.misses, 0);
    assert.ok(swaps > 0);
    return { ...result, swaps, level, transport, geometry: { ...hook.geometry(), ...geometry, input }, box, resume, resumeEvents };
}

/** Replay the recorded packets and clock, without running the policy or noise PRNG. */
export function replayCollierRecording(recording) {
    const { level, seed, geometry, entries, advances, transport } = recording;
    const { scene, hook, handlers, domHandlers } = createScene('panda', false, undefined, geometry?.canvas);
    const { input } = geometry;
    assert.ok(input && [input.x, input.y, input.scaleX, input.scaleY].every(Number.isFinite), 'Recorded input geometry');
    assert.ok(input.scaleX > 0 && input.scaleY > 0);
    scene.session.paused = true;
    hook.advance(0);
    let active = [], resumed = false, clock = 0, cursor = 0, eventCursor = 0;
    for (const entry of entries) {
        while (cursor < advances.length && advances[cursor].gameMs <= entry.timeMs) {
            const advance = advances[cursor++];
            assert.equal(advance.gameMs, clock + advance.ms, 'Recorded clock order');
            hook.advance(advance.ms);
            clock = advance.gameMs;
        }
        assert.equal(clock, entry.timeMs, 'Input follows recorded advance');
        hook.advance(0);
        const type = { touchStart: 'pointerdown', touchMove: 'pointermove', touchEnd: 'pointerup' }[entry.type];
        assert.ok(type, 'Recorded touch type');
        const points = entry.type === 'touchEnd' ? active : entry.points;
        for (const point of points) {
            const delivered = transport[eventCursor++];
            assert.ok(delivered, 'Recorded transport receipt');
            assert.equal(delivered.type, type, 'Recorded transport order');
            domHandlers.get(type)?.({ pointerType: 'touch', clientX: delivered.x, clientY: delivered.y });
            if (resumed) handlers.get(type)({ id: point.id, wasTouch: true,
                x: (delivered.x - input.x) * input.scaleX,
                y: (delivered.y - input.y) * input.scaleY, downTime: 0, upTime: 100 });
        }
        hook.advance(0);
        if (!resumed && entry.type === 'touchEnd') {
            scene.session.paused = false;
            hook.loadLevel(level, seed);
            hook.advance(0);
            resumed = true;
        }
        active = entry.points;
    }
    for (; cursor < advances.length; cursor++) hook.advance(advances[cursor].ms);
    hook.advance(0);
    assert.equal(eventCursor, transport.length, 'Every transport event replayed');
    const snapshot = hook.read();
    // Recordings made before receipts left read() keep them in final.fingerInput; rebuild that legacy shape from the receipts hook.
    if (recording.final?.fingerInput && 'receipts' in recording.final.fingerInput && hook.fingerReceipts) {
        const receipts = hook.fingerReceipts(), legacy = !('target' in (recording.final.fingerInput.receipts?.events?.[0] ?? { target: null }));
        // Legacy events had no `target` field (added with the edge probe).
        snapshot.fingerInput = { ...snapshot.fingerInput, receipts: legacy ? { ...receipts, events: receipts.events.map(event => { const copy = { ...event }; delete copy.target; return copy; }) } : receipts };
    }
    const final = recordedPrecision(snapshot, recording.final);
    return { final, fingerprint: checksum({ entries, final }) };
}

/** Math.sin/cos/hypot/atan2 may differ by a few ULPs across JS runtimes.
 * Keep the original checksum format, but only borrow recorded decimals after
 * independently replaying and checking the whole snapshot. No gameplay field,
 * receipt, clock or discrete value may be substituted to hide a divergence.
 */
function recordedPrecision(actual, recorded) {
    const reconcile = (value, reference, path) => {
        if (/^final\.paths\.\d+\.samples$/.test(path)) {
            equivalentSamples(value, reference, path);
            return reference;
        }
        if (typeof value === 'number' && typeof reference === 'number'
            && (path === 'final.angle' || path.startsWith('final.paths.'))
            && !Number.isInteger(value) && !Number.isInteger(reference)) {
            const tolerance = 32 * Number.EPSILON * Math.max(1, Math.abs(value), Math.abs(reference));
            assert.ok(Number.isFinite(value) && Number.isFinite(reference)
                && Math.abs(value - reference) <= tolerance, `${path}: recorded numerical precision`);
            return reference;
        }
        if (value && reference && typeof value === 'object' && typeof reference === 'object') {
            assert.deepEqual(Object.keys(value), Object.keys(reference), `${path}: recorded structure`);
            return Array.isArray(value)
                ? value.map((item, index) => reconcile(item, reference[index], `${path}.${index}`))
                : Object.fromEntries(Object.entries(value).map(([key, item]) => [key, reconcile(item, reference[key], `${path}.${key}`)]));
        }
        assert.deepEqual(value, reference, `${path}: recorded state`);
        return value;
    };
    return reconcile(actual, recorded, 'final');
}

// Path.append uses ceil(segment length): roundoff at an integer boundary can
// split one linear segment into two. Compare both tables at their arc lengths,
// rather than requiring identical subdivision counts. This affects only the
// static lookup table in the checksum; the simulation still uses Node's table.
function equivalentSamples(actual, recorded, path) {
    for (const samples of [actual, recorded]) {
        assert.ok(Array.isArray(samples) && samples.length > 1, `${path}: samples`);
        for (const [index, sample] of samples.entries()) {
            assert.deepEqual(Object.keys(sample), ['x', 'y', 's']);
            assert.ok(Object.values(sample).every(Number.isFinite), `${path}: finite sample`);
            assert.ok(index === 0 || sample.s > samples[index - 1].s, `${path}: increasing arc length`);
        }
    }
    assert.equal(actual[0].s, recorded[0].s, `${path}: start`);
    assert.equal(actual.at(-1).s, recorded.at(-1).s, `${path}: end`);
    for (const [source, target] of [[actual, recorded], [recorded, actual]]) {
        let cursor = 1;
        for (const sample of source) {
            while (cursor < target.length - 1 && target[cursor].s < sample.s) cursor++;
            const a = target[cursor - 1], b = target[cursor];
            const t = (sample.s - a.s) / (b.s - a.s);
            for (const axis of ['x', 'y']) {
                const interpolated = a[axis] + (b[axis] - a[axis]) * t;
                // Arc-length accumulation errors propagate to coordinates.
                const tolerance = 32 * Number.EPSILON * Math.max(1, source.at(-1).s);
                assert.ok(Math.abs(sample[axis] - interpolated) <= tolerance,
                    `${path} at s=${sample.s}: recorded curve ${axis}`);
            }
        }
    }
}

