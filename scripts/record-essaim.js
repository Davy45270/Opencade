import { writeFileSync } from 'node:fs';
import { Engine } from '../src/engines/essaim/engine.ts';
import { pilot } from '../src/engines/essaim/pilot.ts';
import { observeEssaim } from './essaim-diversity.js';
import { decimal, stateWitness, replay } from '../tests/essaim-replay.ts';
/** Invoked by validate-essaim --record; the search policy stays outside Vitest. */
export function recordEssaim() {
    const records = [];
    for (const seed of [458,28]) for (let level = 0; level < 30; level++) {
        const e = new Engine(level, seed), inputs = [], checkpoints = [];
        const observation = observeEssaim(e, 18000, (engine, frame) => {
            if (frame % 120 === 0) checkpoints.push([frame,...stateWitness(engine)]);
            pilot(engine,frame);
            const entry = [frame,engine.state.target,engine.state.firing ? 1 : 0], previous = inputs.at(-1);
            if (!previous || previous[1] !== entry[1] || previous[2] !== entry[2]) inputs.push(entry);
        });
        checkpoints.push([observation.frames,...stateWitness(e)]);
        if (e.status !== 'won') throw new Error(`Recording failed: ${level+1}/${seed}`);
        const record = { level, seed, inputs, checkpoints, observation, result:[e.state.lives,e.state.score,e.state.fired] };
        replay(record);
        records.push(record);
    }
    writeFileSync('tests/essaim-recordings.ts', '// Generated by nice -n 19 ionice -c3 node scripts/validate-essaim.js --record.\nimport type { EssaimRecording } from \'./essaim-replay\';\nexport const recordings: EssaimRecording[] = '+'[\n'+records.map(r => '    '+decimal(r)).join(',\n')+'\n];\n');
}
